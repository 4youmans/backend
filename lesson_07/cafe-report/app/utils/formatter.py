"""Форматирование сумм и заголовков отчёта."""


def format_kopeks(kopeks: int) -> str:
    """Переводит копейки в строку вида «1 250,00 ₽».

    Args:
        kopeks: Сумма в целых копейках.

    Returns:
        Сумма в рублях с разделителем тысяч и двумя знаками после запятой.
    """
    return f"{kopeks / 100:,.2f} ₽".replace(",", " ").replace(".", ",")


def format_title(text: str, width: int = 40) -> str:
    """Центрирует заголовок с заполнением знаком равенства.

    Args:
        text: Текст заголовка.
        width: Минимальная ширина строки, по умолчанию 40.

    Returns:
        Заголовок с симметричным заполнением.
    """
    return text.center(width, "=")
